console.log(0.1 + 0.2 === 0.3); //  0.300000000000898 === 0.3
console.log((0.1 + 0.2).toFixed(2) === "0.30");

// System will store the value in the binary format as IEEE 754 standard
// 0.1 will be stored in the binary format like: 0.100000000000111
// 0.2 will be stored in the binary format like: 0.100000000000555
// 0.3 will be stored in the binary format like: 0.300000000000898
