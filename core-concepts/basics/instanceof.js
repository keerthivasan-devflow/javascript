// The instanceof operator is used to check whether an object is an instance of a particular constructor or class.

// Example 1
const numbers = Array.of(10, 20, 30);
console.log(numbers instanceof Array);
console.log(numbers instanceof Object);

// Example 2
const customer = {
  name: "Deepika Padukone",
  age: 45,
};
console.log(customer instanceof Array);
console.log(customer instanceof Object);
